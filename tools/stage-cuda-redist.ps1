<#
.SYNOPSIS
  Stages the NVIDIA CUDA runtime DLLs that AiDotNet.Native.CUDA packs.

.DESCRIPTION
  Populates src/AiDotNet.Native.CUDA/runtimes/win-x64/native with the CUDA 12
  runtime AiDotNet.Tensors' CUDA backend needs at run time:
    cudart64_12, cublas64_12, cublasLt64_12, nvrtc64_120_0(+.alt), nvrtc-builtins64_*
  These are gitignored (~770MB) and fetched on demand so the release pipeline can
  build the package without committing the binaries (industry-standard, like the
  other AiDotNet.Native.* packages).

  Source: the official NVIDIA CUDA redistributable archives (no toolkit install
  needed), parsed from redistrib_<version>.json. For local/offline use, pass
  -LocalSource <dir> to copy already-downloaded DLLs instead.

  Each archive's SHA-256 is checked against redistrib_<version>.json, its LICENSE must
  match the committed src/AiDotNet.Native.CUDA/LICENSE.CUDA.txt, and the staged files
  are recorded (component version, licence, SHA-256) in
  src/AiDotNet.Native.CUDA/NATIVE-MANIFEST.json, which ships in the meta package.

.EXAMPLE
  ./tools/stage-cuda-redist.ps1                       # download CUDA 12.6.3 redist
  ./tools/stage-cuda-redist.ps1 -LocalSource C:\cuda  # copy from a local folder
#>
param(
    [string]$CudaVersion = "12.6.3",
    [string]$OutputDir = "$PSScriptRoot/../src/AiDotNet.Native.CUDA/runtimes/win-x64/native",
    [string]$LocalSource = "",
    # Inventory of the staged files (vendor version, licence, SHA-256), packed into the
    # AiDotNet.Native.CUDA meta package. Generated here because the DLLs are not in git.
    [string]$ManifestPath = "$PSScriptRoot/../src/AiDotNet.Native.CUDA/NATIVE-MANIFEST.json"
)

$ErrorActionPreference = "Stop"
$wanted = @("cudart64_", "cublas64_", "cublasLt64_", "nvrtc64_", "nvrtc-builtins64_")
New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null
$licenseFile = Join-Path $PSScriptRoot "../src/AiDotNet.Native.CUDA/LICENSE.CUDA.txt"
$licenseText = "NVIDIA CUDA Toolkit End User License Agreement; the redistributable runtime files are listed in its Attachment A"

function Want([string]$name) { foreach ($w in $wanted) { if ($name -like "$w*") { return $true } } return $false }

function Get-Sha256([string]$path) { (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant() }

# Copies one DLL into the package and returns its manifest entry.
function Stage-File([System.IO.FileInfo]$file) {
    Copy-Item $file.FullName -Destination $OutputDir -Force
    Write-Host "  + $($file.Name)"
    [ordered]@{
        path   = "runtimes/win-x64/native/$($file.Name)"
        size   = $file.Length
        sha256 = Get-Sha256 $file.FullName
    }
}

function Write-Manifest($components) {
    $doc = [ordered]@{
        schemaVersion = 1
        package       = "AiDotNet.Native.CUDA"
        description   = "Inventory of every third-party native file this package redistributes: upstream version, licence and SHA-256. Generated by tools/stage-cuda-redist.ps1 when the NVIDIA redistributables are staged; tools/Test-NativeManifest.ps1 checks it against the staged files before packing."
        components    = @($components)
    }
    $json = $doc | ConvertTo-Json -Depth 8
    [System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($ManifestPath), $json + "`n", [System.Text.UTF8Encoding]::new($false))
    Write-Host "Wrote $ManifestPath"
}

if ($LocalSource) {
    Write-Host "Staging CUDA runtime from local source: $LocalSource"
    $files = @(Get-ChildItem $LocalSource -Filter *.dll | Where-Object { Want $_.Name } | ForEach-Object { Stage-File $_ })
    if ($files.Count -eq 0) { throw "No CUDA runtime DLLs found in $LocalSource" }
    Write-Manifest @([ordered]@{
        name        = "NVIDIA CUDA runtime (staged from a local folder)"
        supplier    = "NVIDIA Corporation"
        version     = "unknown: staged with -LocalSource, not from a versioned NVIDIA redistributable archive"
        license     = $licenseText
        licenseFile = "LICENSE.CUDA.txt"
        upstream    = $LocalSource
        files       = $files
    })
    return
}

$base = "https://developer.download.nvidia.com/compute/cuda/redist"
$manifest = Invoke-RestMethod "$base/redistrib_$CudaVersion.json"
$components = @("cuda_cudart", "libcublas", "cuda_nvrtc")
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) "cuda-redist-$CudaVersion"
New-Item -ItemType Directory -Force -Path $tmp | Out-Null
$committedLicense = Get-Sha256 $licenseFile
$entries = @()

foreach ($component in $components) {
    $archive = $manifest.$component."windows-x86_64"
    $rel = $archive.relative_path
    # A missing component would publish a CUDA package without cuBLAS or nvRTC; fail instead.
    if (-not $rel) { throw "redistrib_$CudaVersion.json has no windows-x86_64 archive for $component" }

    $url = "$base/$rel"
    $zip = Join-Path $tmp (Split-Path $rel -Leaf)
    $extract = Join-Path $tmp $component

    Write-Host "Downloading $component -> $url"
    Invoke-WebRequest $url -OutFile $zip
    # NVIDIA publishes the SHA-256 of every archive in the redistrib JSON; refuse a mismatched download.
    $actual = Get-Sha256 $zip
    if ($actual -ne $archive.sha256.ToLowerInvariant()) {
        throw "SHA-256 mismatch for $url`: expected $($archive.sha256), got $actual"
    }
    Remove-Item $extract -Recurse -Force -ErrorAction SilentlyContinue
    Expand-Archive $zip -DestinationPath $extract -Force

    # The package ships LICENSE.CUDA.txt from the repo; it must be the licence this archive carries.
    $archiveLicense = @(Get-ChildItem $extract -Recurse -File -Filter LICENSE)
    if ($archiveLicense.Count -ne 1) { throw "Expected one LICENSE file in $rel, found $($archiveLicense.Count)" }
    if ((Get-Sha256 $archiveLicense[0].FullName) -ne $committedLicense) {
        throw "The LICENSE in $rel differs from src/AiDotNet.Native.CUDA/LICENSE.CUDA.txt; update the committed licence text from the archive."
    }

    $files = @(Get-ChildItem $extract -Recurse -Filter *.dll | Where-Object { Want $_.Name } | Sort-Object Name | ForEach-Object { Stage-File $_ })
    if ($files.Count -eq 0) { throw "No runtime DLLs found in $rel" }
    $entries += [ordered]@{
        name          = $manifest.$component.name
        supplier      = "NVIDIA Corporation"
        version       = $manifest.$component.version
        license       = $licenseText
        licenseFile   = "LICENSE.CUDA.txt"
        licenseSource = "$base/$($manifest.$component.license_path)"
        upstream      = $url
        archiveSha256 = $actual
        provenance    = "Extracted from the NVIDIA redistributable archive above (CUDA $CudaVersion release), whose SHA-256 was checked against redistrib_$CudaVersion.json."
        files         = $files
    }
}

Write-Manifest $entries
Write-Host "Staged CUDA runtime into $OutputDir"
