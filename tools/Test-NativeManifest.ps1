<#
.SYNOPSIS
  Verifies each AiDotNet.Native.* package's NATIVE-MANIFEST.json against the files on disk.

.DESCRIPTION
  Every native package redistributes third-party binaries, and its NATIVE-MANIFEST.json records the upstream
  version, licence and SHA-256 of each one. This check fails when:
    - a manifest is missing, malformed, or names a different package;
    - a component has no name, version or licence, or names a licence file that does not exist;
    - a listed file is missing, or its size or SHA-256 differs from the manifest;
    - a file under runtimes/ is not listed (a binary would ship without an inventory entry);
    - the same file is listed twice.

  AiDotNet.Native.CUDA keeps its binaries out of git, so its manifest is generated by tools/stage-cuda-redist.ps1.
  The CUDA package is skipped when nothing is staged and fails when DLLs are staged without a manifest.

.PARAMETER Package  Limit the check to these package names (default: every src/AiDotNet.Native.* directory).

.EXAMPLE
  pwsh ./tools/Test-NativeManifest.ps1
  pwsh ./tools/Test-NativeManifest.ps1 -Package AiDotNet.Native.CUDA
#>
param(
    [string[]]$Package = @()
)

$ErrorActionPreference = "Stop"
$srcRoot = Join-Path $PSScriptRoot "../src" | Resolve-Path
$failures = [System.Collections.Generic.List[string]]::new()

$dirs = @(Get-ChildItem -LiteralPath $srcRoot -Directory -Filter "AiDotNet.Native.*" | Sort-Object Name)
if ($Package.Count -gt 0) {
    $dirs = @($dirs | Where-Object { $Package -contains $_.Name })
    $unknown = @($Package | Where-Object { $dirs.Name -notcontains $_ })
    if ($unknown.Count -gt 0) { throw "Unknown native package(s): $($unknown -join ', ')" }
}
if ($dirs.Count -eq 0) { throw "No AiDotNet.Native.* package directories found under $srcRoot" }

foreach ($dir in $dirs) {
    $name = $dir.Name
    $manifestPath = Join-Path $dir.FullName "NATIVE-MANIFEST.json"
    $runtimesDir = Join-Path $dir.FullName "runtimes"
    $onDisk = @()
    if (Test-Path -LiteralPath $runtimesDir) {
        $onDisk = @(Get-ChildItem -LiteralPath $runtimesDir -Recurse -File |
            ForEach-Object { [System.IO.Path]::GetRelativePath($dir.FullName, $_.FullName).Replace('\', '/') })
    }

    if (-not (Test-Path -LiteralPath $manifestPath)) {
        if ($name -eq "AiDotNet.Native.CUDA" -and $onDisk.Count -eq 0) {
            Write-Host "[$name] no staged binaries and no manifest - skipped (run tools/stage-cuda-redist.ps1 to stage)."
            continue
        }
        $failures.Add("[$name] NATIVE-MANIFEST.json is missing.")
        continue
    }

    try { $manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json }
    catch { $failures.Add("[$name] NATIVE-MANIFEST.json is not valid JSON: $($_.Exception.Message)"); continue }

    if ($manifest.schemaVersion -ne 1) { $failures.Add("[$name] unsupported schemaVersion '$($manifest.schemaVersion)'.") }
    if ($manifest.package -ne $name) { $failures.Add("[$name] manifest names package '$($manifest.package)'.") }
    $components = @($manifest.components)
    if ($components.Count -eq 0) { $failures.Add("[$name] manifest lists no components.") }

    $listed = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
    foreach ($component in $components) {
        $label = "[$name/$($component.name)]"
        foreach ($field in @("name", "version", "license")) {
            if ([string]::IsNullOrWhiteSpace([string]$component.$field)) { $failures.Add("$label missing '$field'.") }
        }
        foreach ($field in @("licenseFile", "thirdPartyNoticesFile")) {
            $file = [string]$component.$field
            if ($file -and -not (Test-Path -LiteralPath (Join-Path $dir.FullName $file))) {
                $failures.Add("$label $field '$file' does not exist.")
            }
        }
        $files = @($component.files)
        if ($files.Count -eq 0) { $failures.Add("$label lists no files.") }
        foreach ($entry in $files) {
            $rel = [string]$entry.path
            if (-not $listed.Add($rel)) { $failures.Add("$label '$rel' is listed more than once."); continue }
            $full = Join-Path $dir.FullName $rel
            if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { $failures.Add("$label '$rel' does not exist."); continue }
            $item = Get-Item -LiteralPath $full
            if ($item.Length -ne [long]$entry.size) {
                $failures.Add("$label '$rel' is $($item.Length) bytes; the manifest records $($entry.size).")
            }
            $hash = (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash.ToLowerInvariant()
            if ($hash -ne ([string]$entry.sha256).ToLowerInvariant()) {
                $failures.Add("$label '$rel' SHA-256 is $hash; the manifest records $($entry.sha256).")
            }
        }
    }
    foreach ($rel in $onDisk) {
        if (-not $listed.Contains($rel)) { $failures.Add("[$name] '$rel' is not listed in NATIVE-MANIFEST.json.") }
    }
    Write-Host "[$name] checked $($listed.Count) file(s) against NATIVE-MANIFEST.json."
}

if ($failures.Count -gt 0) {
    $failures | ForEach-Object { Write-Host "::error::$_" }
    throw "$($failures.Count) native manifest problem(s) found."
}
Write-Host "Every native manifest matches its package files."
