using System;
using AiDotNet.Tensors.Engines.DevicePrimitives;
using AiDotNet.Tensors.Engines.DevicePrimitives.Cpu;
using AiDotNet.Tensors.LinearAlgebra;

namespace AiDotNet.Tensors.Engines.DirectGpu.CUDA;

/// <summary>
/// High-level cuRAND-backed <see cref="IDeviceRng"/>. Every algorithm has a CPU generator (created through
/// <see cref="CpuDeviceRng.Create"/>) that produces cuRAND's numbers, so a (seed, subsequence, offset) gives the same
/// values with or without a GPU. When <c>libcurand</c> and a CUDA device are present, some calls are generated on
/// the device instead, with the CPU generator's position advanced to match.
///
/// <para><b>Philox.</b> When the native cuRAND library is loadable and the calling thread has a current CUDA
/// context, the seed and offset are forwarded to <c>libcurand</c>'s Philox generator; otherwise
/// <see cref="CpuPhiloxGenerator"/> runs. This is #219's cross-backend determinism point; PyTorch's CPU and CUDA
/// generators diverge at the same seed.</para>
///
/// <para><b>MRG32k3a and plain Sobol32 (#1204).</b> Uniform calls are generated by cuRAND on the device, which is
/// bit-identical to <see cref="CpuMrg32k3aGenerator"/> and <see cref="CpuSobolGenerator"/>, when all of these
/// hold; otherwise the CPU generator produces the call:</para>
/// <list type="bullet">
/// <item>the device is worth it. A Sobol call needs at least <see cref="SobolDeviceMinimumLength"/> values, below
/// which the device round trip is no faster than the CPU. An MRG32k3a generator costs about 44 ms to set up on the
/// device after every seed or offset change, then generates a million values in about 0.1 ms, so it is set up
/// only once the uniform calls since the last set-up add up to <see cref="Mrg32k3aSetupBreakEven"/> values (about
/// what the CPU generates in the set-up time), and from then on every call that continues where the device
/// generator stands runs on the device, whatever its size;</item>
/// <item>the subsequence is 0 (cuRAND has no subsequence for either generator);</item>
/// <item>for MRG32k3a, every call since the offset was last set consumed uniforms only: a normal call moves
/// individual streams, a position no cuRAND offset can express (<see cref="CpuMrg32k3aGenerator.OffsetIsExact"/>);</item>
/// <item>for Sobol, the call is whole points that stay below point 2^32 (the 32-bit sequence's period);</item>
/// <item>CUDA device 0 can be reached. The device work runs in its primary context, which this class retains once
/// and holds for the life of the process.</item>
/// </list>
/// <para>Each instance keeps its cuRAND generator and device buffer between calls, because setting a generator up
/// is most of the cost (about 44 ms for an MRG32k3a generator on a GTX 1660 Ti, against about 0.1 ms to then
/// generate a million values); <see cref="Dispose"/> frees them, and so does the
/// finalizer when an instance is dropped.</para>
/// <para>Normal and Bernoulli calls of these algorithms always run on the CPU generator: cuRAND's device normals
/// go through the GPU's <c>log</c>/<c>sin</c>/<c>erfinv</c>, which differ from the CPU's in the last bits and would
/// break the same-bits-on-every-backend contract. Scrambled Sobol is this library's own scramble and has no cuRAND
/// equivalent, so it is CPU-only.</para>
/// </summary>
public sealed class CuRand : IDeviceRng, IDisposable
{
    /// <summary>The default for <see cref="SobolDeviceMinimumLength"/>, measured on a GTX 1660 Ti (see #1204's PR).</summary>
    internal const int DefaultSobolDeviceMinimumLength = 1 << 18;

    /// <summary>The default for <see cref="Mrg32k3aSetupBreakEven"/>: about 4 million values, which the CPU generator
    /// takes about 58 ms to produce on the measuring machine, against about 44 ms to set up the device generator.</summary>
    internal const ulong DefaultMrg32k3aSetupBreakEven = 1UL << 22;

    private readonly IDeviceRng _cpuFallback;
    private DeviceGenerator? _device;

    /// <summary>True when <c>libcurand</c> is loadable on this host.
    /// Useful for telemetry; the wrapper degrades gracefully either
    /// way.</summary>
    public static bool IsAvailable => CuRandNative.IsAvailable;

    /// <summary>True when MRG32k3a and Sobol uniforms can be generated on a CUDA device from any thread: cuRAND
    /// loads and device 0's primary context can be retained.</summary>
    internal static bool DeviceGenerationAvailable => CuRandNative.IsAvailable && PrimaryContext.Value != IntPtr.Zero;

    /// <summary>The smallest Sobol uniform call that is generated on the device.</summary>
    internal int SobolDeviceMinimumLength { get; set; } = DefaultSobolDeviceMinimumLength;

    /// <summary>How many MRG32k3a uniform values must have been asked for, counting the current call, before the
    /// device generator is set up. Renting the CPU until the rent equals the set-up cost keeps the total within twice
    /// the best choice made in hindsight, whatever the call pattern.</summary>
    internal ulong Mrg32k3aSetupBreakEven { get; set; } = DefaultMrg32k3aSetupBreakEven;

    // MRG32k3a uniform values produced on the CPU since the device generator was last set up.
    private ulong _mrgDemandSinceSetup;

    /// <summary>Whether the most recent <c>Uniform</c> call on this instance was generated on the device.</summary>
    internal bool LastUniformUsedDevice { get; private set; }

    /// <inheritdoc/>
    public DeviceRngAlgorithm Algorithm { get; }

    /// <inheritdoc/>
    public ulong Seed => _cpuFallback.Seed;

    /// <inheritdoc/>
    public ulong Offset
    {
        get => _cpuFallback.Offset;
        set => _cpuFallback.Offset = value;
    }

    /// <inheritdoc/>
    public ulong Subsequence
    {
        get => _cpuFallback.Subsequence;
        set => _cpuFallback.Subsequence = value;
    }

    /// <summary>Constructs a CUDA-backed RNG for <paramref name="algo"/>; see the class remarks for which calls
    /// run on the device.</summary>
    /// <param name="seed">The seed.</param>
    /// <param name="algo">The algorithm. Anything <see cref="CpuDeviceRng.Create"/> does not support throws
    /// <see cref="NotSupportedException"/>, rather than silently producing another algorithm's numbers.</param>
    /// <param name="subsequence">The subsequence (for Sobol, the first dimension).</param>
    /// <param name="offset">The starting offset (for Sobol, the first point).</param>
    /// <param name="dimensions">Dimensions per point, for the Sobol generators only.</param>
    public CuRand(ulong seed, DeviceRngAlgorithm algo = DeviceRngAlgorithm.Philox,
        ulong subsequence = 0, ulong offset = 0, int dimensions = 1)
    {
        Algorithm = algo;
        _cpuFallback = CpuDeviceRng.Create(algo, seed, subsequence, offset, dimensions);
    }

    /// <inheritdoc/>
    public void Uniform(Tensor<float> output)
    {
        if (output is null) throw new ArgumentNullException(nameof(output));
        LastUniformUsedDevice = CuRandNative.IsAvailable && (Algorithm == DeviceRngAlgorithm.Philox
            ? TryDeviceUniform(output, normal: false, mean: 0f, stddev: 1f)
            : TryExactDeviceUniform(output));
        if (!LastUniformUsedDevice) _cpuFallback.Uniform(output);
    }

    /// <inheritdoc/>
    public void Uniform(Tensor<double> output)
    {
        if (output is null) throw new ArgumentNullException(nameof(output));
        LastUniformUsedDevice = CuRandNative.IsAvailable && (Algorithm == DeviceRngAlgorithm.Philox
            ? TryDeviceUniformDouble(output, normal: false, mean: 0, stddev: 1)
            : TryExactDeviceUniform(output));
        if (!LastUniformUsedDevice) _cpuFallback.Uniform(output);
    }

    /// <inheritdoc/>
    public void Normal(Tensor<float> output, float mean = 0f, float stddev = 1f)
    {
        if (!CuRandNative.IsAvailable || !TryDeviceUniform(output, normal: true, mean: mean, stddev: stddev))
            _cpuFallback.Normal(output, mean, stddev);
    }

    /// <inheritdoc/>
    public void Normal(Tensor<double> output, double mean = 0, double stddev = 1)
    {
        if (!CuRandNative.IsAvailable || !TryDeviceUniformDouble(output, normal: true, mean: mean, stddev: stddev))
            _cpuFallback.Normal(output, mean, stddev);
    }

    /// <inheritdoc/>
    public void Bernoulli(Tensor<float> output, float p) => _cpuFallback.Bernoulli(output, p);

    // ------------------------------------------------------------------ MRG32k3a and Sobol32 on the device

    /// <summary>Device 0's primary context, retained once and never released: releasing it after each call would
    /// destroy and recreate the context (and cuRAND's state in it) every time. Zero when there is no usable device.</summary>
    private static readonly Lazy<IntPtr> PrimaryContext = new(RetainPrimaryContext);

    private static IntPtr RetainPrimaryContext()
    {
        try
        {
            if (CuBlasNative.cuInit(0) != CudaResult.Success) return IntPtr.Zero;
            if (CuBlasNative.cuDeviceGetCount(out int count) != CudaResult.Success || count < 1) return IntPtr.Zero;
            if (CuBlasNative.cuDeviceGet(out int device, 0) != CudaResult.Success) return IntPtr.Zero;
            return CuBlasNative.cuDevicePrimaryCtxRetain(out var context, device) == CudaResult.Success ? context : IntPtr.Zero;
        }
        catch
        {
            // No driver (DllNotFound, EntryPointNotFound, BadImageFormat): the CPU generator runs.
            return IntPtr.Zero;
        }
    }

    /// <summary>Where a device call starts and how far it moves the CPU generator.</summary>
    internal readonly struct DevicePlan
    {
        public DevicePlan(CuRandNative.GeneratorType type, ulong offset, uint dimensions, ulong advance)
        {
            Type = type; Offset = offset; Dimensions = dimensions; Advance = advance;
        }

        public CuRandNative.GeneratorType Type { get; }
        public ulong Offset { get; }
        public uint Dimensions { get; }
        public ulong Advance { get; }
    }

    /// <summary>
    /// Decides whether a call of <paramref name="length"/> values goes to the device, and where. Pure: it reads the CPU
    /// generator's position and this instance's setup bookkeeping and touches no CUDA state, so the routing rules are
    /// tested on machines without a GPU.
    /// </summary>
    internal bool TryPlanExactDevice(int length, out DevicePlan plan)
    {
        plan = default;
        if (length == 0) return false;
        return _cpuFallback switch
        {
            CpuMrg32k3aGenerator mrg => TryPlanMrg32k3a(mrg, length, out plan),
            CpuSobolGenerator sobol => TryPlanSobol(sobol, length, out plan),
            _ => false,
        };
    }

    private bool TryPlanMrg32k3a(CpuMrg32k3aGenerator mrg, int length, out DevicePlan plan)
    {
        plan = default;
        if (mrg.Subsequence != 0 || !mrg.OffsetIsExact) return false;
        ulong offset = mrg.Offset;
        if (offset > ulong.MaxValue - (ulong)length) return false;
        // Continuing where the device generator stands costs no set-up, so it always pays.
        if (_device?.NextOffset != offset)
        {
            ulong demand = _mrgDemandSinceSetup + (ulong)length;
            if (demand < Mrg32k3aSetupBreakEven)
            {
                _mrgDemandSinceSetup = demand;
                return false;
            }
            _mrgDemandSinceSetup = 0;
        }
        plan = new DevicePlan(CuRandNative.GeneratorType.PseudoMrg32K3A, offset, 1, (ulong)length);
        return true;
    }

    private bool TryPlanSobol(CpuSobolGenerator sobol, int length, out DevicePlan plan)
    {
        plan = default;
        if (sobol.Algorithm != DeviceRngAlgorithm.Sobol || sobol.Subsequence != 0) return false;
        if (length % sobol.Dimensions != 0 || length < SobolDeviceMinimumLength) return false;
        // The CPU generator wraps at point 2^32; keep the device to calls that never reach the wrap.
        ulong points = (ulong)(length / sobol.Dimensions);
        const ulong Period = 1UL << 32;
        if (sobol.Offset > Period - points) return false;
        plan = new DevicePlan(CuRandNative.GeneratorType.QuasiSobol32, sobol.Offset, (uint)sobol.Dimensions, points);
        return true;
    }

    private bool TryExactDeviceUniform(Tensor<float> output)
    {
        if (!TryPlanExactDevice(output.Length, out var plan)) return false;
        bool generated;
        using (var lease = output.LeaseWritable())
        {
            unsafe
            {
                fixed (float* host = lease.Span)
                    generated = GenerateOnDevice(plan, (IntPtr)host, (ulong)output.Length, isDouble: false);
            }
        }
        if (generated) CommitPlan(plan);
        return generated;
    }

    private bool TryExactDeviceUniform(Tensor<double> output)
    {
        if (!TryPlanExactDevice(output.Length, out var plan)) return false;
        bool generated;
        using (var lease = output.LeaseWritable())
        {
            unsafe
            {
                fixed (double* host = lease.Span)
                    generated = GenerateOnDevice(plan, (IntPtr)host, (ulong)output.Length, isDouble: true);
            }
        }
        if (generated) CommitPlan(plan);
        return generated;
    }

    /// <summary>
    /// Moves the CPU generator past the values the device produced, so both stay in lockstep: by the value count for
    /// MRG32k3a, by whole points for Sobol (see <see cref="DevicePlan.Advance"/>).
    /// </summary>
    internal void CommitPlan(DevicePlan plan) => _cpuFallback.Offset = plan.Offset + plan.Advance;

    /// <summary>
    /// Generates <paramref name="count"/> uniforms into host memory with this instance's cuRAND device generator.
    /// False, with the host memory unspecified, when any step fails; the caller then fills it on the CPU.
    /// </summary>
    /// <remarks>
    /// The generator is kept between calls because setting it up is most of the cost: an MRG32k3a generator
    /// computes its 81,920 stream states after every seed or offset change (about 44 ms on a GTX 1660 Ti), after
    /// which a million values take about 0.1 ms. So the offset is only set when the CPU generator's position is not
    /// where the device generator already stands; consecutive device calls just continue. Everything runs in the
    /// primary context, which is never released, so the generator and its buffer can be freed from any thread.
    /// </remarks>
    private bool GenerateOnDevice(DevicePlan plan, IntPtr host, ulong count, bool isDouble)
    {
        var primary = PrimaryContext.Value;
        if (primary == IntPtr.Zero) return false;
        var device = _device ??= new DeviceGenerator();
        bool pushed = false;
        try
        {
            if (CuBlasNative.cuCtxPushCurrent(primary) != CudaResult.Success) return false;
            pushed = true;

            ulong bytes = count * (isDouble ? (ulong)sizeof(double) : (ulong)sizeof(float));
            if (!device.EnsureBuffer(bytes)) return false;
            if (device.Handle == IntPtr.Zero)
            {
                if (CuRandNative.curandCreateGenerator(out var generator, plan.Type) != CuRandNative.Status.Success) return false;
                device.Handle = generator;
                var configured = plan.Type == CuRandNative.GeneratorType.QuasiSobol32
                    ? CuRandNative.curandSetQuasiRandomGeneratorDimensions(generator, plan.Dimensions)
                    : CuRandNative.curandSetPseudoRandomGeneratorSeed(generator, Seed);
                if (configured != CuRandNative.Status.Success) { device.Release(); return false; }
            }

            // The copy below runs on the context's current stream (or the legacy stream); generate on the same one
            // so it is ordered after the kernel.
            if (CuRandNative.curandSetStream(device.Handle, CudaCurrentStream.ForCurrentContext()) != CuRandNative.Status.Success) return false;
            if (device.NextOffset != plan.Offset)
            {
                if (CuRandNative.curandSetGeneratorOffset(device.Handle, plan.Offset) != CuRandNative.Status.Success) return false;
            }

            device.NextOffset = null;      // unknown until the generate succeeds
            var status = isDouble
                ? CuRandNative.curandGenerateUniformDouble(device.Handle, device.Buffer, count)
                : CuRandNative.curandGenerateUniform(device.Handle, device.Buffer, count);
            if (status != CuRandNative.Status.Success) return false;
            // cuRAND advances its offset by the values generated, or for Sobol by the points.
            device.NextOffset = plan.Offset + plan.Advance;
            return CudaNativeBindings.cuMemcpyDtoH(host, device.Buffer, bytes) == CudaResult.Success;
        }
        catch
        {
            return false;
        }
        finally
        {
            if (pushed) CuBlasNative.cuCtxPopCurrent(out _);
        }
    }

    /// <summary>Releases this instance's cuRAND device generator and device buffer, if it made any. The CPU
    /// generator keeps working; a later device call creates them again.</summary>
    public void Dispose()
    {
        _device?.Dispose();
        _device = null;
    }

    /// <summary>
    /// A cuRAND device generator and its output buffer, both in the primary context. The finalizer frees them when
    /// the <see cref="CuRand"/> is dropped without being disposed; that is safe from the finalizer thread because
    /// the primary context is retained for the life of the process.
    /// </summary>
    private sealed class DeviceGenerator : IDisposable
    {
        public IntPtr Handle;
        public IntPtr Buffer;
        public ulong BufferBytes;
        /// <summary>The offset the generator continues from, or null when it must be set before the next call.</summary>
        public ulong? NextOffset;

        /// <summary>Makes <see cref="Buffer"/> at least <paramref name="bytes"/> long. The primary context must be current.</summary>
        public bool EnsureBuffer(ulong bytes)
        {
            if (BufferBytes >= bytes) return true;
            if (Buffer != IntPtr.Zero)
            {
                CudaNativeBindings.cuMemFree(Buffer);
                Buffer = IntPtr.Zero;
                BufferBytes = 0;
            }
            if (CudaNativeBindings.cuMemAlloc(out var buffer, bytes) != CudaResult.Success) return false;
            Buffer = buffer;
            BufferBytes = bytes;
            return true;
        }

        /// <summary>Frees the generator and buffer. The primary context must be current.</summary>
        public void Release()
        {
            if (Handle != IntPtr.Zero) CuRandNative.curandDestroyGenerator(Handle);
            if (Buffer != IntPtr.Zero) CudaNativeBindings.cuMemFree(Buffer);
            Handle = IntPtr.Zero;
            Buffer = IntPtr.Zero;
            BufferBytes = 0;
            NextOffset = null;
        }

        private void ReleaseInPrimaryContext()
        {
            if (Handle == IntPtr.Zero && Buffer == IntPtr.Zero) return;
            var primary = PrimaryContext.Value;
            if (primary == IntPtr.Zero) return;
            try
            {
                if (CuBlasNative.cuCtxPushCurrent(primary) != CudaResult.Success) return;
                try { Release(); }
                finally { CuBlasNative.cuCtxPopCurrent(out _); }
            }
            catch
            {
                // The driver is unloading; the process is ending and the memory goes with it.
            }
        }

        public void Dispose()
        {
            ReleaseInPrimaryContext();
            GC.SuppressFinalize(this);
        }

        ~DeviceGenerator() => ReleaseInPrimaryContext();
    }

    // ------------------------------------------------------------------ Philox on the device

    private bool TryDeviceUniform(Tensor<float> output, bool normal, float mean, float stddev)
    {
        if (!CuRandNative.IsAvailable) return false;
        // Subsequence-bypass: cuRAND's Philox API has no subsequence
        // parameter — `curandSetPseudoRandomGeneratorSeed` accepts only
        // the seed, and offset is a per-stream counter advancement, not
        // the subsequence dimension that managed Philox 4x32-10 supports.
        // When the caller asks for a non-zero subsequence, the device
        // path's bits would silently diverge from CpuPhiloxGenerator's
        // — breaking the cross-backend determinism contract that
        // CuRand class-doc promises. Fall back to CPU so the contract
        // holds.
        // MRG32k3a and Sobol normals stay on their CPU generators (see the class remarks); their uniforms go
        // through TryExactDeviceUniform.
        if (Algorithm != DeviceRngAlgorithm.Philox || _cpuFallback.Subsequence != 0) return false;
        IntPtr dPtr = IntPtr.Zero;
        IntPtr generator = IntPtr.Zero;
        try
        {
            ulong bytes = (ulong)output.Length * sizeof(float);
            if (CudaNativeBindings.cuMemAlloc(out dPtr, bytes) != AiDotNet.Tensors.Engines.CudaResult.Success) return false;

            if (CuRandNative.curandCreateGenerator(out generator, CuRandNative.GeneratorType.PseudoPhilox4_32_10) != CuRandNative.Status.Success) return false;
            CuRandNative.curandSetPseudoRandomGeneratorSeed(generator, _cpuFallback.Seed);
            CuRandNative.curandSetGeneratorOffset(generator, _cpuFallback.Offset);

            var status = normal
                ? CuRandNative.curandGenerateNormal(generator, dPtr, (ulong)output.Length, mean, stddev)
                : CuRandNative.curandGenerateUniform(generator, dPtr, (ulong)output.Length);
            if (status != CuRandNative.Status.Success) return false;

            unsafe
            {
                using var outputKeep1 = new KeepAliveScope(output);
                fixed (float* hostPtr = output.AsWritableSpanUnmarked())
                {
                    if (CudaNativeBindings.cuMemcpyDtoH((IntPtr)hostPtr, dPtr, bytes) != AiDotNet.Tensors.Engines.CudaResult.Success) return false;
                }
            }
            // Advance offset by Philox 4x32 BLOCK count (one block produces 4 outputs).
            // Both cuRAND and our managed Philox treat the offset as a block counter,
            // so increment by ceil(N/4) — element-counter advancement would over-skip
            // by 4× and break the cross-call determinism contract.
            _cpuFallback.Offset += ((ulong)output.Length + 3) / 4;
            return true;
        }
        catch
        {
            return false;
        }
        finally
        {
            if (generator != IntPtr.Zero) CuRandNative.curandDestroyGenerator(generator);
            if (dPtr != IntPtr.Zero) CudaNativeBindings.cuMemFree(dPtr);
        }
    }

    private bool TryDeviceUniformDouble(Tensor<double> output, bool normal, double mean, double stddev)
    {
        if (!CuRandNative.IsAvailable) return false;
        // Same subsequence-bypass as TryDeviceUniform — cuRAND's Philox
        // doesn't accept a subsequence parameter, so a non-zero
        // subsequence on this side must fall back to CPU to preserve
        // bit-equivalence.
        // MRG32k3a and Sobol normals stay on their CPU generators (see the class remarks); their uniforms go
        // through TryExactDeviceUniform.
        if (Algorithm != DeviceRngAlgorithm.Philox || _cpuFallback.Subsequence != 0) return false;
        IntPtr dPtr = IntPtr.Zero;
        IntPtr generator = IntPtr.Zero;
        try
        {
            ulong bytes = (ulong)output.Length * sizeof(double);
            if (CudaNativeBindings.cuMemAlloc(out dPtr, bytes) != AiDotNet.Tensors.Engines.CudaResult.Success) return false;

            if (CuRandNative.curandCreateGenerator(out generator, CuRandNative.GeneratorType.PseudoPhilox4_32_10) != CuRandNative.Status.Success) return false;
            CuRandNative.curandSetPseudoRandomGeneratorSeed(generator, _cpuFallback.Seed);
            CuRandNative.curandSetGeneratorOffset(generator, _cpuFallback.Offset);

            var status = normal
                ? CuRandNative.curandGenerateNormalDouble(generator, dPtr, (ulong)output.Length, mean, stddev)
                : CuRandNative.curandGenerateUniformDouble(generator, dPtr, (ulong)output.Length);
            if (status != CuRandNative.Status.Success) return false;

            unsafe
            {
                using var outputKeep2 = new KeepAliveScope(output);
                fixed (double* hostPtr = output.AsWritableSpanUnmarked())
                {
                    if (CudaNativeBindings.cuMemcpyDtoH((IntPtr)hostPtr, dPtr, bytes) != AiDotNet.Tensors.Engines.CudaResult.Success) return false;
                }
            }
            _cpuFallback.Offset += (ulong)output.Length;
            return true;
        }
        catch
        {
            return false;
        }
        finally
        {
            if (generator != IntPtr.Zero) CuRandNative.curandDestroyGenerator(generator);
            if (dPtr != IntPtr.Zero) CudaNativeBindings.cuMemFree(dPtr);
        }
    }
}
