// Single-kernel emission of a row-fused program (CodegenRowFusion): one warp per row, the
// row's sources held in registers across every pass, each statistic a shuffle reduction.
//
// It is a partial of PtxAffineEmitter so that every per-element operation -- the pre-bias,
// exp and square, the epilogue, the activations -- is the SAME instruction sequence the
// multi-pass kernels emit. The only things that differ are where values live and when they
// are combined, which is exactly what fusion is supposed to change.

using System;
using System.Collections.Generic;
using System.Globalization;
using AiDotNet.Tensors.Engines.Compilation.Codegen.Ir;

namespace AiDotNet.Tensors.Engines.Compilation.Codegen.Ptx;

public sealed partial class PtxAffineEmitter
{
    /// <summary>
    /// Emits <paramref name="plan"/> as one kernel named <paramref name="kernelName"/>, whose
    /// parameters are <see cref="CodegenRowFusionPlan.Parameters"/> in order. Launch with
    /// <see cref="LaunchBlocks"/> blocks of <see cref="LaunchBlockX"/> threads.
    /// </summary>
    public string EmitRowProgram(CodegenRowFusionPlan plan, string kernelName, int computeMajor, int computeMinor)
    {
        if (plan is null) throw new ArgumentNullException(nameof(plan));
        if (string.IsNullOrWhiteSpace(kernelName)) throw new ArgumentException("Kernel needs a name.", nameof(kernelName));

        const int Lanes = CodegenWarpReduction.Lanes;
        int perLane = plan.PerLane;
        long threads = (long)plan.Rows * Lanes;
        long blocks = (threads + BlockThreads - 1) / BlockThreads;

        _sb.Clear(); _body.Clear(); _r = _f = _p = _rd = 0;
        EmittedLoads = 0; ElidedGuards = 0; IndirectIndexLoads = 0; AtomicStores = 0;
        ExtraOutputStores = 0; VectorisedStores = 0; VectorisedLoads = 0;
        SharedMemoryBytes = 0; StagedOperands = "none"; CoarsenedLanes = 1; LoopedAxes = 0;
        UsedTwoDimensionalBlock = false; WarpReduced = true; Unrolled = true;
        LaunchBlockX = BlockThreads; LaunchBlockY = 1; LaunchBlockThreads = BlockThreads;
        LaunchBlocks = checked((uint)blocks);

        _sb.Append(".version ").Append(PtxIsaVersionFor(computeMajor, computeMinor)).Append('\n')
           .Append(".target sm_").Append(I(computeMajor)).Append(I(computeMinor)).Append('\n')
           .Append(".address_size 64\n\n")
           .Append("// generated by PtxAffineEmitter.EmitRowProgram: ")
           .Append(plan.Program.Description).Append(", one warp per row\n")
           .Append(".visible .entry ").Append(kernelName).Append("(\n");
        for (int i = 0; i < plan.Parameters.Count; i++)
            _sb.Append("    .param .u64 p").Append(I(i)).Append(i == plan.Parameters.Count - 1 ? "\n" : ",\n");
        _sb.Append(")\n{\n");

        var basePtr = new Dictionary<string, string>(StringComparer.Ordinal);
        for (int i = 0; i < plan.Parameters.Count; i++)
        {
            string reg = NextRd();
            L($"ld.param.u64 {reg}, [p{I(i)}];");
            basePtr[plan.Parameters[i]] = reg;
        }

        string ctaid = NextR(), tid = NextR(), gid = NextR(), row = NextR(), lane = NextR();
        L($"mov.u32 {ctaid}, %ctaid.x;");
        L($"mov.u32 {tid}, %tid.x;");
        L($"mad.lo.u32 {gid}, {ctaid}, {I(BlockThreads)}, {tid};");
        L($"shr.u32 {row}, {gid}, 5;");
        L($"and.b32 {lane}, {gid}, 31;");
        // Rows x 32 threads in 256-thread blocks: the guard retires whole warps.
        string guard = NextP();
        L($"setp.ge.u32 {guard}, {row}, {I(plan.Rows)};");
        L($"@{guard} bra END;");
        string leader = NextP();
        L($"setp.eq.u32 {leader}, {lane}, 0;");

        string rowBytes = NextRd(), laneBytes = NextRd(), rowStatBytes = NextRd();
        L($"mul.wide.u32 {rowBytes}, {row}, {I(plan.Width * 4)};");
        L($"mul.wide.u32 {laneBytes}, {lane}, 4;");
        L($"mul.wide.u32 {rowStatBytes}, {row}, 4;");

        // Per-thread base addresses, built once per tensor on first use.
        var matrixPtr = new Dictionary<string, string>(StringComparer.Ordinal);
        var featurePtr = new Dictionary<string, string>(StringComparer.Ordinal);
        string MatrixPtr(string name)
        {
            if (matrixPtr.TryGetValue(name, out string? p)) return p;
            string a = NextRd(), b = NextRd();
            L($"add.s64 {a}, {basePtr[name]}, {rowBytes};");
            L($"add.s64 {b}, {a}, {laneBytes};");
            return matrixPtr[name] = b;
        }
        string FeaturePtr(string name)
        {
            if (featurePtr.TryGetValue(name, out string? p)) return p;
            string a = NextRd();
            L($"add.s64 {a}, {basePtr[name]}, {laneBytes};");
            return featurePtr[name] = a;
        }

        // Values a thread holds: element t of a matrix or feature (lane + 32t), and per-row
        // statistics. A source matrix is loaded once and then lives in registers.
        var held = new Dictionary<string, string>(StringComparer.Ordinal);
        var rowStat = new Dictionary<string, string>(StringComparer.Ordinal);
        string Operand(CodegenKernelSpec pass, int input, int t)
        {
            string name = pass.Inputs[input].Name;
            switch (plan.Kinds[name])
            {
                case CodegenRowOperandKind.Row:
                    if (rowStat.TryGetValue(name, out string? stat)) return stat;
                    string addr = NextRd(), v = NextF();
                    L($"add.s64 {addr}, {basePtr[name]}, {rowStatBytes};");
                    L($"ld.global.nc.f32 {v}, [{addr}];");
                    EmittedLoads++;
                    return rowStat[name] = v;
                case CodegenRowOperandKind.Feature:
                {
                    string key = name + "#" + I(t);
                    if (held.TryGetValue(key, out string? f)) return f;
                    string value = NextF();
                    L($"ld.global.nc.f32 {value}, [{FeaturePtr(name)}+{I(t * Lanes * 4)}];");
                    EmittedLoads++;
                    return held[key] = value;
                }
                default:
                {
                    string key = name + "#" + I(t);
                    if (held.TryGetValue(key, out string? m)) return m;
                    string value = NextF();
                    L($"ld.global.nc.f32 {value}, [{MatrixPtr(name)}+{I(t * Lanes * 4)}];");
                    EmittedLoads++;
                    return held[key] = value;
                }
            }
        }

        // The body of one term, exactly as the affine emitter forms it: product, pre-bias,
        // pre-reduction. Always a fresh register, because an in-place activation (ReLU)
        // must never overwrite a held source.
        string Term(CodegenKernelSpec pass, int t)
        {
            string product = NextF();
            L($"mov.f32 {product}, {Operand(pass, pass.ProductInputs[0], t)};");
            for (int k = 1; k < pass.ProductInputs.Count; k++)
            {
                string next = NextF();
                L($"mul.rn.f32 {next}, {product}, {Operand(pass, pass.ProductInputs[k], t)};");
                product = next;
            }
            if (pass.PreBiasInput is { } pb)
            {
                string pv = Operand(pass, pb, t), shifted = NextF();
                if (pass.PreBiasScale == 1.0) L($"add.rn.f32 {shifted}, {product}, {pv};");
                else L($"fma.rn.f32 {shifted}, {pv}, {F32(pass.PreBiasScale)}, {product};");
                product = shifted;
            }
            if (pass.PreReduce == CodegenPreReduceOp.Square)
            {
                string sq = NextF();
                L($"mul.rn.f32 {sq}, {product}, {product};");
                product = sq;
            }
            else if (pass.PreReduce == CodegenPreReduceOp.Exp)
            {
                string scaled = NextF(), e = NextF();
                L($"mul.rn.f32 {scaled}, {product}, 0f3FB8AA3B;");
                L($"ex2.approx.f32 {e}, {scaled};");
                product = e;
            }
            return product;
        }

        // The epilogue in the spec's order: scale, offset, bias, scale, post-scale,
        // post-bias, activation.
        string Epilogue(CodegenKernelSpec pass, string acc, int t)
        {
            void Apply(string op, string operand)
            {
                string r = NextF();
                L($"{op} {r}, {acc}, {operand};");
                acc = r;
            }
            if (pass.ReduceScale != 1.0) Apply("mul.rn.f32", F32(pass.ReduceScale));
            if (pass.ReduceOffset != 0.0) Apply("add.rn.f32", F32(pass.ReduceOffset));
            if (pass.BiasInput is { } bias) Apply("add.rn.f32", Operand(pass, bias, t));
            if (pass.ScaleInput is { } scale) Apply("mul.rn.f32", Operand(pass, scale, t));
            if (pass.PostScaleInput is { } postScale) Apply("mul.rn.f32", Operand(pass, postScale, t));
            if (pass.PostBiasInput is { } postBias) Apply("add.rn.f32", Operand(pass, postBias, t));
            return EmitActivation(pass.Activation, acc);
        }

        foreach (var pass in plan.Program.Passes)
        {
            string output = pass.Output.Name;
            if (pass.Reduce != CodegenReduceKind.None)
            {
                bool max = pass.Reduce == CodegenReduceKind.Max;
                string combine = max ? "max.f32" : "add.rn.f32";
                string acc = NextF();
                L(max ? $"mov.f32 {acc}, 0fFF800000;" : $"mov.f32 {acc}, 0f00000000;");
                for (int t = 0; t < perLane; t++)
                {
                    string next = NextF();
                    L($"{combine} {next}, {acc}, {Term(pass, t)};");
                    acc = next;
                }
                for (int offset = Lanes / 2; offset >= 1; offset /= 2)
                {
                    string bits = NextR(), otherBits = NextR(), other = NextF(), combined = NextF();
                    L($"mov.b32 {bits}, {acc};");
                    L($"shfl.sync.bfly.b32 {otherBits}, {bits}, {I(offset)}, 31, 0xffffffff;");
                    L($"mov.b32 {other}, {otherBits};");
                    L($"{combine} {combined}, {acc}, {other};");
                    acc = combined;
                }
                string statistic = Epilogue(pass, acc, -1);
                rowStat[output] = statistic;
                string addr = NextRd();
                L($"add.s64 {addr}, {basePtr[output]}, {rowStatBytes};");
                L($"@{leader} st.global.f32 [{addr}], {statistic};");
            }
            else
            {
                string ptr = MatrixPtr(output);
                for (int t = 0; t < perLane; t++)
                {
                    string value = Epilogue(pass, Term(pass, t), t);
                    L($"st.global.f32 [{ptr}+{I(t * Lanes * 4)}], {value};");
                }
            }
        }

        _body.Append("END:\n    ret;\n}\n");
        return Assemble();
    }
}
