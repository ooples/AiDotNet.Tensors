// Elementwise kernels of RUNTIME length (#890 phase 4a): the pointwise family -- unary, binary, scalar-parameter,
// column-broadcast -- as declared bodies over operands, one module per operator rather than one per shape. The
// length, the broadcast width and any float scalars are kernel parameters; the host picks the 128-bit path when the
// length and every pointer allow it and says so in a parameter, so the branch is uniform.

using System;
using System.Collections.Generic;
using AiDotNet.Tensors.Engines.Compilation.Codegen.Ir;

namespace AiDotNet.Tensors.Engines.Compilation.Codegen.Ptx;

/// <summary>
/// An elementwise operator of runtime length: <paramref name="Body"/> over <paramref name="Inputs"/> tensor operands
/// (and any runtime scalars it reads), written to one output. <paramref name="ColumnBroadcastInput"/>, when not -1, is
/// an operand read at <c>i % columns</c> (a bias over the last axis).
/// </summary>
public sealed record CodegenElementwiseSpec(string Name, int Inputs, CodegenExpr Body, int ColumnBroadcastInput = -1)
{
    /// <summary>Runtime float parameters the body reads.</summary>
    public int Scalars => Body.ScalarCount();
}

public sealed partial class PtxAffineEmitter
{
    /// <summary>Threads per block of an elementwise kernel.</summary>
    public const int ElementwiseBlockThreads = 256;

    /// <summary>
    /// Emits <paramref name="spec"/> as a kernel named <paramref name="kernelName"/>. Parameters, in order: each input
    /// pointer, the output pointer, <c>n</c> (u32), <c>vectorized</c> (u32: nonzero for four elements a thread with
    /// 128-bit accesses -- the host's promise that n % 4 == 0 and every pointer is 16-byte aligned), then
    /// <c>columns</c> (u32) when an operand is column-broadcast (the 128-bit path also needs columns % 4 == 0), then
    /// each scalar (f32). Launch <see cref="ElementwiseBlockThreads"/>-thread blocks covering n, or n / 4 when
    /// vectorized.
    /// </summary>
    public string EmitElementwise(CodegenElementwiseSpec spec, string kernelName, int computeMajor, int computeMinor)
    {
        if (spec is null) throw new ArgumentNullException(nameof(spec));
        if (string.IsNullOrWhiteSpace(kernelName)) throw new ArgumentException("Kernel needs a name.", nameof(kernelName));
        if (spec.Inputs < 0) throw new ArgumentOutOfRangeException(nameof(spec));
        foreach (int operand in spec.Body.Operands())
            if (operand >= spec.Inputs) throw new ArgumentException("The body reads operand " + operand + " of " + spec.Inputs + ".", nameof(spec));
        bool broadcast = spec.ColumnBroadcastInput >= 0;
        if (broadcast && spec.ColumnBroadcastInput >= spec.Inputs)
            throw new ArgumentException("The broadcast operand is not an input.", nameof(spec));

        _sb.Clear(); _body.Clear(); _calledFunctions.Clear(); _r = _f = _p = _rd = 0;
        LaunchBlockX = ElementwiseBlockThreads; LaunchBlockY = 1; LaunchBlockThreads = ElementwiseBlockThreads;
        LaunchBlocks = 0;   // runtime: the host covers n
        int scalars = spec.Scalars;
        var parameters = new List<string>();
        for (int i = 0; i < spec.Inputs; i++) parameters.Add(".param .u64 in" + I(i));
        parameters.Add(".param .u64 out");
        parameters.Add(".param .u32 n");
        parameters.Add(".param .u32 vectorized");
        if (broadcast) parameters.Add(".param .u32 columns");
        for (int i = 0; i < scalars; i++) parameters.Add(".param .f32 s" + I(i));

        _sb.Append(".version ").Append(PtxIsaVersionFor(computeMajor, computeMinor)).Append('\n')
           .Append(".target sm_").Append(I(computeMajor)).Append(I(computeMinor)).Append('\n')
           .Append(".address_size 64\n\n")
           .Append("// generated by PtxAffineEmitter.EmitElementwise: ").Append(spec.Name).Append(" = ")
           .Append(spec.Body.ToString()).Append('\n')
           .Append(".visible .entry ").Append(kernelName).Append("(\n");
        for (int i = 0; i < parameters.Count; i++)
            _sb.Append("    ").Append(parameters[i]).Append(i == parameters.Count - 1 ? "\n" : ",\n");
        _sb.Append(")\n.maxntid ").Append(I(ElementwiseBlockThreads)).Append(", 1, 1\n{\n");

        var inputs = new string[spec.Inputs];
        for (int i = 0; i < spec.Inputs; i++)
        {
            inputs[i] = NextRd();
            L($"ld.param.u64 {inputs[i]}, [in{I(i)}];");
        }
        string output = NextRd(), n = NextR(), vectorized = NextR(), columns = NextR();
        L($"ld.param.u64 {output}, [out];");
        L($"ld.param.u32 {n}, [n];");
        L($"ld.param.u32 {vectorized}, [vectorized];");
        if (broadcast) L($"ld.param.u32 {columns}, [columns];");
        _scalarRegisters = new string[scalars];
        for (int i = 0; i < scalars; i++)
        {
            _scalarRegisters[i] = NextF();
            L($"ld.param.f32 {_scalarRegisters[i]}, [s{I(i)}];");
        }

        string ctaid = NextR(), tid = NextR(), gid = NextR(), scalarPath = NextP();
        L($"mov.u32 {ctaid}, %ctaid.x;");
        L($"mov.u32 {tid}, %tid.x;");
        L($"mad.lo.u32 {gid}, {ctaid}, {I(ElementwiseBlockThreads)}, {tid};");
        L($"setp.eq.u32 {scalarPath}, {vectorized}, 0;");
        L($"@{scalarPath} bra SCALAR;");

        // ---- four elements a thread, 128-bit.
        {
            string groups = NextR(), outside = NextP(), first = NextR(), bytes = NextRd();
            L($"shr.u32 {groups}, {n}, 2;");
            L($"setp.ge.u32 {outside}, {gid}, {groups};");
            L($"@{outside} bra END;");
            L($"shl.b32 {first}, {gid}, 2;");
            L($"mul.wide.u32 {bytes}, {gid}, 16;");
            var lanes = new string[spec.Inputs][];
            for (int i = 0; i < spec.Inputs; i++)
            {
                string at = NextRd();
                if (i == spec.ColumnBroadcastInput)
                {
                    string column = NextR(), columnBytes = NextRd();
                    L($"rem.u32 {column}, {first}, {columns};");
                    L($"mul.wide.u32 {columnBytes}, {column}, 4;");
                    L($"add.s64 {at}, {inputs[i]}, {columnBytes};");
                }
                else L($"add.s64 {at}, {inputs[i]}, {bytes};");
                lanes[i] = new[] { NextF(), NextF(), NextF(), NextF() };
                L($"ld.global.nc.v4.f32 {{{string.Join(", ", lanes[i])}}}, [{at}];");
            }
            var results = new string[4];
            for (int c = 0; c < 4; c++)
            {
                int lane = c;
                results[c] = EmitBody(spec.Body, operand => lanes[operand][lane]);
            }
            string store = NextRd();
            L($"add.s64 {store}, {output}, {bytes};");
            L($"st.global.v4.f32 [{store}], {{{string.Join(", ", results)}}};");
            L("bra END;");
        }

        // ---- one element a thread.
        _body.Append("SCALAR:\n");
        {
            string outside = NextP(), bytes = NextRd();
            L($"setp.ge.u32 {outside}, {gid}, {n};");
            L($"@{outside} bra END;");
            L($"mul.wide.u32 {bytes}, {gid}, 4;");
            var values = new string[spec.Inputs];
            for (int i = 0; i < spec.Inputs; i++)
            {
                string at = NextRd();
                if (i == spec.ColumnBroadcastInput)
                {
                    string column = NextR(), columnBytes = NextRd();
                    L($"rem.u32 {column}, {gid}, {columns};");
                    L($"mul.wide.u32 {columnBytes}, {column}, 4;");
                    L($"add.s64 {at}, {inputs[i]}, {columnBytes};");
                }
                else L($"add.s64 {at}, {inputs[i]}, {bytes};");
                values[i] = NextF();
                L($"ld.global.nc.f32 {values[i]}, [{at}];");
            }
            string result = EmitBody(spec.Body, operand => values[operand]);
            string store = NextRd();
            L($"add.s64 {store}, {output}, {bytes};");
            L($"st.global.f32 [{store}], {result};");
        }
        _body.Append("END:\n    ret;\n}\n");
        _scalarRegisters = null;
        return Assemble();
    }
}
