    private static void EmitRmsNormResidualCpu(StringBuilder sb)
    {
        sb.AppendLine(@"    /// <summary>
    /// Compile-time generated fused residual-add + RMSNorm forward pass:
    /// computes s = x + residual, invRms = rsqrt(mean(s^2) + eps), output = s * invRms * gamma in two tight row passes
    /// without allocating an external temporary when residualSumOut is omitted, or writing residualSumOut in place.
    /// </summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static void RmsNormResidualForward(
        ReadOnlySpan<float> input,
        ReadOnlySpan<float> residual,
        ReadOnlySpan<float> gamma,
        Span<float> output,
        Span<float> residualSumOut,
        Span<float> rmsOut,
        int rows,
        int cols,
        float epsilon)
    {
        if (rows <= 0 || cols <= 0) return;
        int total = checked(rows * cols);
        if (input.Length < total || residual.Length < total || output.Length < total || gamma.Length < cols)
            throw new ArgumentException(""Buffer lengths do not match [rows, cols] for RmsNormResidualForward."");
        bool writeSum = !residualSumOut.IsEmpty;
        if (writeSum && residualSumOut.Length < total)
            throw new ArgumentException(""residualSumOut is smaller than rows * cols."", nameof(residualSumOut));
        bool writeRms = !rmsOut.IsEmpty;
        if (writeRms && rmsOut.Length < rows)
            throw new ArgumentException(""rmsOut is smaller than rows."", nameof(rmsOut));

        float invCols = 1.0f / cols;
        for (int r = 0; r < rows; r++)
        {
            int rowOffset = r * cols;
            var xRow = input.Slice(rowOffset, cols);
            var resRow = residual.Slice(rowOffset, cols);
            var yRow = output.Slice(rowOffset, cols);
            float sumSq = 0.0f;
            int c = 0;
#if NET8_0_OR_GREATER
            if (Avx.IsSupported && cols >= 8)
            {
                Vector256<float> acc = Vector256<float>.Zero;
                int simdCols = cols & ~7;
                if (writeSum)
                {
                    var sRow = residualSumOut.Slice(rowOffset, cols);
                    for (; c < simdCols; c += 8)
                    {
                        var sVec = Avx.Add(
                            global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(xRow, c),
                            global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(resRow, c));
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.WriteVector256(sRow, c, sVec);
                        acc = GeneratedKernelSimdMath.Fma256(sVec, sVec, acc);
                    }
                }
                else
                {
                    for (; c < simdCols; c += 8)
                    {
                        var sVec = Avx.Add(
                            global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(xRow, c),
                            global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(resRow, c));
                        acc = GeneratedKernelSimdMath.Fma256(sVec, sVec, acc);
                    }
                }
                sumSq = GeneratedKernelSimdMath.HorizontalSum256(acc);
            }
#endif
            if (c == 0 && Vector.IsHardwareAccelerated && cols >= Vector<float>.Count)
            {
                int lanes = Vector<float>.Count;
                int simdCols = cols - (cols % lanes);
                var vx = MemoryMarshal.Cast<float, Vector<float>>(xRow.Slice(0, simdCols));
                var vr = MemoryMarshal.Cast<float, Vector<float>>(resRow.Slice(0, simdCols));
                var vAcc = Vector<float>.Zero;
                if (writeSum)
                {
                    var vs = MemoryMarshal.Cast<float, Vector<float>>(residualSumOut.Slice(rowOffset, simdCols));
                    for (int v = 0; v < vx.Length; v++)
                    {
                        var sv = vx[v] + vr[v];
                        vs[v] = sv;
                        vAcc += sv * sv;
                    }
                }
                else
                {
                    for (int v = 0; v < vx.Length; v++)
                    {
                        var sv = vx[v] + vr[v];
                        vAcc += sv * sv;
                    }
                }
                sumSq = GeneratedKernelSimdMath.HorizontalSumPortable(vAcc);
                c = simdCols;
            }

            if (writeSum)
            {
                var sRow = residualSumOut.Slice(rowOffset, cols);
                for (; c < cols; c++)
                {
                    float s = xRow[c] + resRow[c];
                    sRow[c] = s;
                    sumSq += s * s;
                }
            }
            else
            {
                for (; c < cols; c++)
                {
                    float s = xRow[c] + resRow[c];
                    sumSq += s * s;
                }
            }

            float rms = GeneratedKernelSimdMath.SqrtScalar(sumSq * invCols + epsilon);
            if (writeRms) rmsOut[r] = rms;
            float invRms = 1.0f / rms;

            int k = 0;
#if NET8_0_OR_GREATER
            if (Avx.IsSupported && cols >= 8)
            {
                var vInv = Vector256.Create(invRms);
                int simdCols = cols & ~7;
                if (writeSum)
                {
                    var sRow = residualSumOut.Slice(rowOffset, cols);
                    for (; k < simdCols; k += 8)
                    {
                        var sVec = global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(sRow, k);
                        var gVec = global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(gamma, k);
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.WriteVector256(yRow, k, Avx.Multiply(Avx.Multiply(sVec, vInv), gVec));
                    }
                }
                else
                {
                    for (; k < simdCols; k += 8)
                    {
                        var sVec = Avx.Add(
                            global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(xRow, k),
                            global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(resRow, k));
                        var gVec = global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(gamma, k);
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.WriteVector256(yRow, k, Avx.Multiply(Avx.Multiply(sVec, vInv), gVec));
                    }
                }
            }
#endif
            for (; k < cols; k++)
            {
                float s = writeSum ? residualSumOut[rowOffset + k] : (xRow[k] + resRow[k]);
                yRow[k] = s * invRms * gamma[k];
            }
        }
    }

    /// <summary>
    /// Fused backward for residual-add + RMSNorm: computes d(x + residual) (shared gradient for both branches) and accumulates gradGamma.
    /// </summary>
    public static void RmsNormResidualBackward(
        ReadOnlySpan<float> gradOutput,
        ReadOnlySpan<float> input,
        ReadOnlySpan<float> residual,
        ReadOnlySpan<float> gamma,
        ReadOnlySpan<float> rms,
        Span<float> gradInputAndResidual,
        Span<float> gradGamma,
        int rows,
        int cols)
    {
        if (rows <= 0 || cols <= 0) return;
        int total = checked(rows * cols);
        if (gradOutput.Length < total || input.Length < total || residual.Length < total ||
            gradInputAndResidual.Length < total || gamma.Length < cols || rms.Length < rows)
            throw new ArgumentException(""Buffer lengths do not match [rows, cols] for RmsNormResidualBackward."");

        bool computeGradGamma = !gradGamma.IsEmpty;
        if (computeGradGamma) gradGamma.Slice(0, cols).Clear();
        float invCols = 1.0f / cols;

        for (int r = 0; r < rows; r++)
        {
            int rowOffset = r * cols;
            float invRms = 1.0f / rms[r];
            float invRms3 = invRms * invRms * invRms;
            float dot = 0.0f;
            for (int c = 0; c < cols; c++)
            {
                float s = input[rowOffset + c] + residual[rowOffset + c];
                float dy = gradOutput[rowOffset + c];
                dot += dy * gamma[c] * s;
                if (computeGradGamma)
                    gradGamma[c] += dy * s * invRms;
            }

            float scale = dot * invCols * invRms3;
            for (int c = 0; c < cols; c++)
            {
                float s = input[rowOffset + c] + residual[rowOffset + c];
                gradInputAndResidual[rowOffset + c] = gradOutput[rowOffset + c] * gamma[c] * invRms - s * scale;
            }
        }
    }
");
    }

    private static void EmitLayerNormResidualCpu(StringBuilder sb)
    {
        sb.AppendLine(@"    /// <summary>
    /// Compile-time generated fused residual-add + LayerNorm forward pass:
    /// s = x + residual; output = ((s - mean(s)) / sqrt(var(s) + eps)) * gamma + beta.
    /// </summary>
    public static void LayerNormResidualForward(
        ReadOnlySpan<float> input,
        ReadOnlySpan<float> residual,
        ReadOnlySpan<float> gamma,
        ReadOnlySpan<float> beta,
        Span<float> output,
        Span<float> meanOut,
        Span<float> invStdOut,
        int rows,
        int cols,
        float epsilon)
    {
        if (rows <= 0 || cols <= 0) return;
        int total = checked(rows * cols);
        if (input.Length < total || residual.Length < total || output.Length < total || gamma.Length < cols || beta.Length < cols)
            throw new ArgumentException(""Buffer lengths do not match [rows, cols] for LayerNormResidualForward."");

        bool writeMean = !meanOut.IsEmpty;
        bool writeInvStd = !invStdOut.IsEmpty;
        float invCols = 1.0f / cols;

        for (int r = 0; r < rows; r++)
        {
            int rowOffset = r * cols;
            var xRow = input.Slice(rowOffset, cols);
            var resRow = residual.Slice(rowOffset, cols);
            var yRow = output.Slice(rowOffset, cols);

            float sum = 0.0f;
            int c = 0;
#if NET8_0_OR_GREATER
            if (Avx.IsSupported && cols >= 8)
            {
                var acc = Vector256<float>.Zero;
                int simdCols = cols & ~7;
                for (; c < simdCols; c += 8)
                {
                    var sVec = Avx.Add(
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(xRow, c),
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(resRow, c));
                    acc = Avx.Add(acc, sVec);
                }
                sum = GeneratedKernelSimdMath.HorizontalSum256(acc);
            }
#endif
            for (; c < cols; c++) sum += xRow[c] + resRow[c];
            float mean = sum * invCols;

            float varSum = 0.0f;
            c = 0;
#if NET8_0_OR_GREATER
            if (Avx.IsSupported && cols >= 8)
            {
                var vMean = Vector256.Create(mean);
                var accVar = Vector256<float>.Zero;
                int simdCols = cols & ~7;
                for (; c < simdCols; c += 8)
                {
                    var diff = Avx.Subtract(
                        Avx.Add(
                            global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(xRow, c),
                            global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(resRow, c)),
                        vMean);
                    accVar = GeneratedKernelSimdMath.Fma256(diff, diff, accVar);
                }
                varSum = GeneratedKernelSimdMath.HorizontalSum256(accVar);
            }
#endif
            for (; c < cols; c++)
            {
                float d = (xRow[c] + resRow[c]) - mean;
                varSum += d * d;
            }

            float invStd = 1.0f / GeneratedKernelSimdMath.SqrtScalar(varSum * invCols + epsilon);
            if (writeMean) meanOut[r] = mean;
            if (writeInvStd) invStdOut[r] = invStd;

            c = 0;
#if NET8_0_OR_GREATER
            if (Avx.IsSupported && cols >= 8)
            {
                var vMean = Vector256.Create(mean);
                var vInvStd = Vector256.Create(invStd);
                int simdCols = cols & ~7;
                for (; c < simdCols; c += 8)
                {
                    var sVec = Avx.Add(
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(xRow, c),
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(resRow, c));
                    var norm = Avx.Multiply(Avx.Subtract(sVec, vMean), vInvStd);
                    var gVec = global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(gamma, c);
                    var bVec = global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(beta, c);
                    global::AiDotNet.Tensors.Engines.Simd.SimdKernels.WriteVector256(
                        yRow, c, GeneratedKernelSimdMath.Fma256(norm, gVec, bVec));
                }
            }
#endif
            for (; c < cols; c++)
            {
                float norm = ((xRow[c] + resRow[c]) - mean) * invStd;
                yRow[c] = norm * gamma[c] + beta[c];
            }
        }
    }

    /// <summary>
    /// Fused backward for residual-add + LayerNorm: computes shared d(x + residual), gradGamma, and gradBeta.
    /// </summary>
    public static void LayerNormResidualBackward(
        ReadOnlySpan<float> gradOutput,
        ReadOnlySpan<float> input,
        ReadOnlySpan<float> residual,
        ReadOnlySpan<float> gamma,
        ReadOnlySpan<float> mean,
        ReadOnlySpan<float> invStd,
        Span<float> gradInputAndResidual,
        Span<float> gradGamma,
        Span<float> gradBeta,
        int rows,
        int cols)
    {
        if (rows <= 0 || cols <= 0) return;
        int total = checked(rows * cols);
        if (gradOutput.Length < total || input.Length < total || residual.Length < total ||
            gradInputAndResidual.Length < total || gamma.Length < cols || mean.Length < rows || invStd.Length < rows)
            throw new ArgumentException(""Buffer lengths do not match [rows, cols] for LayerNormResidualBackward."");

        bool hasGammaGrad = !gradGamma.IsEmpty;
        bool hasBetaGrad = !gradBeta.IsEmpty;
        if (hasGammaGrad) gradGamma.Slice(0, cols).Clear();
        if (hasBetaGrad) gradBeta.Slice(0, cols).Clear();
        float invCols = 1.0f / cols;

        for (int r = 0; r < rows; r++)
        {
            int rowOffset = r * cols;
            float m = mean[r];
            float rstd = invStd[r];
            float sumDyGamma = 0.0f;
            float sumDyGammaXhat = 0.0f;
            for (int c = 0; c < cols; c++)
            {
                float dy = gradOutput[rowOffset + c];
                float xhat = ((input[rowOffset + c] + residual[rowOffset + c]) - m) * rstd;
                float dyg = dy * gamma[c];
                sumDyGamma += dyg;
                sumDyGammaXhat += dyg * xhat;
                if (hasGammaGrad) gradGamma[c] += dy * xhat;
                if (hasBetaGrad) gradBeta[c] += dy;
            }

            float meanDyG = sumDyGamma * invCols;
            float meanDyGXhat = sumDyGammaXhat * invCols;
            for (int c = 0; c < cols; c++)
            {
                float xhat = ((input[rowOffset + c] + residual[rowOffset + c]) - m) * rstd;
                gradInputAndResidual[rowOffset + c] = rstd * (gradOutput[rowOffset + c] * gamma[c] - meanDyG - xhat * meanDyGXhat);
            }
        }
    }
");
    }

    private static void EmitBiasActivationRowCpu(StringBuilder sb)
    {
        sb.AppendLine(@"    /// <summary>
    /// Fused row-broadcast bias + activation: output[r, c] = act(input[r, c] + bias[c]).
    /// activationKind: 0 = None, 1 = ReLU, 2 = GELU, 3 = Swish/SiLU, 4 = Sigmoid, 5 = Tanh.
    /// </summary>
    public static void BiasActivationRowForward(
        ReadOnlySpan<float> input,
        ReadOnlySpan<float> bias,
        Span<float> output,
        int rows,
        int cols,
        int activationKind)
    {
        if (rows <= 0 || cols <= 0) return;
        int total = checked(rows * cols);
        if (input.Length < total || output.Length < total || bias.Length < cols)
            throw new ArgumentException(""Buffer lengths do not match [rows, cols] for BiasActivationRowForward."");

        for (int r = 0; r < rows; r++)
        {
            int rowOffset = r * cols;
            var xRow = input.Slice(rowOffset, cols);
            var yRow = output.Slice(rowOffset, cols);
            int c = 0;
#if NET8_0_OR_GREATER
            if (Avx.IsSupported && Avx2.IsSupported && cols >= 8)
            {
                int simdCols = cols & ~7;
                for (; c < simdCols; c += 8)
                {
                    var z = Avx.Add(
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(xRow, c),
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(bias, c));
                    Vector256<float> res = activationKind switch
                    {
                        1 => Avx.Max(Vector256<float>.Zero, z),
                        2 => GeneratedKernelSimdMath.Gelu256(z),
                        3 => GeneratedKernelSimdMath.Swish256(z),
                        4 => global::AiDotNet.Tensors.Engines.Simd.SimdKernels.FastSigmoid256(z),
                        5 => global::AiDotNet.Tensors.Engines.Simd.SimdKernels.FastTanh256(z),
                        _ => z
                    };
                    global::AiDotNet.Tensors.Engines.Simd.SimdKernels.WriteVector256(yRow, c, res);
                }
            }
#endif
            for (; c < cols; c++)
            {
                float z = xRow[c] + bias[c];
                yRow[c] = activationKind switch
                {
                    1 => GeneratedKernelSimdMath.ReluScalar(z),
                    2 => GeneratedKernelSimdMath.GeluScalar(z),
                    3 => GeneratedKernelSimdMath.SwishScalar(z),
                    4 => GeneratedKernelSimdMath.SigmoidScalar(z),
                    5 => GeneratedKernelSimdMath.TanhScalar(z),
                    _ => z
                };
            }
        }
    }
");
    }

    private static void EmitRotaryPositionEmbeddingCpu(StringBuilder sb)
    {
        sb.AppendLine(@"    /// <summary>
    /// Fused split-half Rotary Positional Embedding (RoPE):
    /// y[i] = x[i] * cos[i] - x[i + halfDim] * sin[i], y[i + halfDim] = x[i + halfDim] * cos[i] + x[i] * sin[i].
    /// </summary>
    public static void RotaryPositionEmbeddingSplitHalf(
        ReadOnlySpan<float> input,
        ReadOnlySpan<float> cos,
        ReadOnlySpan<float> sin,
        Span<float> output,
        int outerCount,
        int seqLen,
        int headDim,
        bool inverseAdjoint = false)
    {
        if (outerCount <= 0 || seqLen <= 0 || headDim <= 0) return;
        if ((headDim & 1) != 0) throw new ArgumentException(""headDim must be even for RoPE."", nameof(headDim));
        int halfDim = headDim >> 1;
        int total = checked(outerCount * seqLen * headDim);
        if (input.Length < total || output.Length < total)
            throw new ArgumentException(""Input/output buffers are smaller than outerCount * seqLen * headDim."");
        int trigStride = cos.Length >= seqLen * headDim ? headDim : halfDim;
        if (cos.Length < seqLen * halfDim || sin.Length < seqLen * halfDim)
            throw new ArgumentException(""cos/sin tables are smaller than seqLen * (headDim / 2)."");

        float sinSign = inverseAdjoint ? -1.0f : 1.0f;
        for (int o = 0; o < outerCount; o++)
        {
            for (int s = 0; s < seqLen; s++)
            {
                int baseIdx = (o * seqLen + s) * headDim;
                int trigIdx = s * trigStride;
                var x0 = input.Slice(baseIdx, halfDim);
                var x1 = input.Slice(baseIdx + halfDim, halfDim);
                var y0 = output.Slice(baseIdx, halfDim);
                var y1 = output.Slice(baseIdx + halfDim, halfDim);
                var cRow = cos.Slice(trigIdx, halfDim);
                var sRow = sin.Slice(trigIdx, halfDim);

                int i = 0;
#if NET8_0_OR_GREATER
                if (Avx.IsSupported && halfDim >= 8)
                {
                    var vSign = Vector256.Create(sinSign);
                    int simd = halfDim & ~7;
                    for (; i < simd; i += 8)
                    {
                        var vx0 = global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(x0, i);
                        var vx1 = global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(x1, i);
                        var vc = global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(cRow, i);
                        var vs = Avx.Multiply(global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(sRow, i), vSign);
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.WriteVector256(
                            y0, i, Avx.Subtract(Avx.Multiply(vx0, vc), Avx.Multiply(vx1, vs)));
                        global::AiDotNet.Tensors.Engines.Simd.SimdKernels.WriteVector256(
                            y1, i, Avx.Add(Avx.Multiply(vx1, vc), Avx.Multiply(vx0, vs)));
                    }
                }
#endif
                for (; i < halfDim; i++)
                {
                    float sv = sRow[i] * sinSign;
                    float cv = cRow[i];
                    float a = x0[i];
                    float b = x1[i];
                    y0[i] = a * cv - b * sv;
                    y1[i] = b * cv + a * sv;
                }
            }
        }
    }
");
    }

    private static void EmitLogSoftmaxCrossEntropyCpu(StringBuilder sb)
    {
        sb.AppendLine(@"    /// <summary>
    /// Compile-time generated fused LogSoftmax + Cross-Entropy forward &amp; optional fused gradient:
    /// computes exact row max and log-sum-exp without materializing an intermediate [rows, cols] log-softmax tensor.
    /// Returns mean cross-entropy loss across active rows (target row mass &gt; 0).
    /// </summary>
    public static float LogSoftmaxCrossEntropyForward(
        ReadOnlySpan<float> logits,
        ReadOnlySpan<float> targetProbs,
        Span<float> rowMaxOut,
        Span<float> rowLogSumExpOut,
        int rows,
        int cols,
        out int activeRows)
    {
        activeRows = 0;
        if (rows <= 0 || cols <= 0) return 0.0f;
        int total = checked(rows * cols);
        if (logits.Length < total || targetProbs.Length < total)
            throw new ArgumentException(""logits and targetProbs must contain at least rows * cols elements."");

        bool saveStats = !rowMaxOut.IsEmpty && !rowLogSumExpOut.IsEmpty;
        double totalLoss = 0.0;

        for (int r = 0; r < rows; r++)
        {
            int rowOffset = r * cols;
            var zRow = logits.Slice(rowOffset, cols);
            var tRow = targetProbs.Slice(rowOffset, cols);

            float rowMax = zRow[0];
            for (int c = 1; c < cols; c++)
            {
                if (zRow[c] > rowMax) rowMax = zRow[c];
            }

            float sumExp = 0.0f;
            int k = 0;
#if NET8_0_OR_GREATER
            if (Avx.IsSupported && Avx2.IsSupported && cols >= 8)
            {
                var vMax = Vector256.Create(rowMax);
                var acc = Vector256<float>.Zero;
                int simdCols = cols & ~7;
                for (; k < simdCols; k += 8)
                {
                    var shifted = Avx.Subtract(global::AiDotNet.Tensors.Engines.Simd.SimdKernels.ReadVector256(zRow, k), vMax);
                    acc = Avx.Add(acc, global::AiDotNet.Tensors.Engines.Simd.SimdKernels.FastExp256(shifted));
                }
                sumExp = GeneratedKernelSimdMath.HorizontalSum256(acc);
            }
#endif
