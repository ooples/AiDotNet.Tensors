using System;

namespace AiDotNet.Tensors.Tests.TestHelpers;

internal static class PtxText
{
    internal static int CountOccurrences(string text, string value)
    {
        int count = 0;
        int offset = 0;
        while ((offset = text.IndexOf(value, offset, StringComparison.Ordinal)) >= 0)
        {
            count++;
            offset += value.Length;
        }

        return count;
    }
}
